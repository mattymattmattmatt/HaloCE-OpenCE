#!/bin/sh
# Writes guest_syscall_names.h into the build's work folder ($1): the guest's
# system call numbers (port/android/include/halo_guest_syscall.h) by name,
# for the report.
set -eu
repository=$(cd -- "$(dirname -- "$0")/../../../.." && pwd)
{
	echo "/* generated by port/ps5/probe/guest/prebuild.sh */"
	echo "static const char *const guest_syscall_names[] = {"
	sed -n 's/^#define GUEST_SYS_\([A-Za-z0-9_]*\) \([0-9][0-9]*\)$/\t[\2] = "\1",/p' \
		"$repository/port/android/include/halo_guest_syscall.h"
	echo "};"
} > "$1/guest_syscall_names.h"

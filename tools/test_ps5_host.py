"""Runs the PS5 host's C test of its translations between the guest's Linux
system call interface and the console's FreeBSD
(port/ps5/host/host_syscall_tables.c, port/ps5/tests/host_syscall_tables_test.c)
with the build machine's C compiler: the tables need no system, and their
FreeBSD numbers (port/ps5/host/freebsd_abi.h) are checked against the SDK's
headers by the console's build (host_syscall.c). Also runs the C test of
the host's rules that need no console (port/ps5/host/host_rules_ps5.c,
port/ps5/tests/host_rules_ps5_test.c), and checks that the generated weak
import stubs (tools/ps5_build.py) compile, one for each function of a host
import table."""
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
HOST = ROOT / "port" / "ps5" / "host"
TESTS = ROOT / "port" / "ps5" / "tests"

sys.path.insert(0, str(ROOT))
from tools.ps5_build import import_stubs_text  # noqa: E402


def compiler():
    for name in ("clang", "cc", "gcc"):
        path = shutil.which(name)
        if path:
            return path
    return None


def test_host_syscall_tables(tmp_path):
    cc = compiler()
    if not cc:
        pytest.skip("no C compiler")
    binary = tmp_path / "host_syscall_tables_test"
    subprocess.run(
        [cc, "-std=c11", "-Wall", "-Wextra", "-Werror", "-O1",
         f"-I{ROOT / 'port' / 'android' / 'include'}", f"-I{HOST}",
         str(TESTS / "host_syscall_tables_test.c"), str(HOST / "host_syscall_tables.c"),
         "-o", str(binary)],
        check=True,
    )
    result = subprocess.run([str(binary)], capture_output=True, text=True)
    assert result.returncode == 0, result.stdout + result.stderr


def test_host_rules(tmp_path):
    cc = compiler()
    if not cc:
        pytest.skip("no C compiler")
    binary = tmp_path / "host_rules_ps5_test"
    subprocess.run(
        [cc, "-std=c11", "-Wall", "-Wextra", "-Werror", "-O1", f"-I{HOST}",
         str(TESTS / "host_rules_ps5_test.c"), str(HOST / "host_rules_ps5.c"), "-lm",
         "-o", str(binary)],
        check=True,
    )
    result = subprocess.run([str(binary)], capture_output=True, text=True)
    assert result.returncode == 0, result.stdout + result.stderr


def test_import_stubs(tmp_path):
    table = """/* generated by tools/android_imports.py; do not edit */
static const struct { const char *name; void *function; } imports[] =
{
\t{ "host_syscall", (void *)host_syscall },
\t{ "hostposix_stat", (void *)posix_stat },
};
"""
    text = import_stubs_text(table)
    assert "__attribute__((weak)) long host_syscall(" in text
    assert "__attribute__((weak)) long posix_stat(" in text
    assert '"hostposix_stat"' in text
    with pytest.raises(ValueError):
        import_stubs_text("no table here")
    cc = compiler()
    if not cc:
        pytest.skip("no C compiler")
    source = tmp_path / "host_import_stubs.c"
    source.write_text(text, encoding="utf-8")
    subprocess.run([cc, "-std=c11", "-Wall", "-Wextra", "-Werror", "-c", str(source), "-o", str(tmp_path / "stubs.o")],
                   check=True)
